#!/usr/bin/env python3
"""
Extract EyeLink blink benchmark intervals from ASC files.

Project directory convention (25 Hz analysis)
---------------------------------------------
Video:
    /Volumes/Empra9/Videos_25/<VP_NAME>

Original pipeline results:
    /Volumes/Empra9/Ergebnisse25/<VP_NAME>/Analyse/
        Run_25hz_FullCalib_<suffix>/

EyeLink ASC input:
    /Volumes/Empra9/Ergebnisse25/<VP_NAME>/<VP_NAME><digits>.asc

Output generated by this script:
    /Volumes/Empra9/Ergebnisse25/<VP_NAME>/test25/
        eyelink_blink_benchmark.csv
        eyelink_trial_markers.csv

The script uses every EBLINK event as an EyeLink blink benchmark event.
No duration filtering or physiological classification is applied.

Time alignment
--------------
EyeLink tracker timestamps are NOT directly matched to video timestamps.
For every trial, the script subtracts that trial's EyeLink fixation-start or
stimulus-start marker and exports trial-relative times in milliseconds and
seconds. These relative columns can be plotted together with video-derived
results whose time zero is the corresponding video fixation/stimulus start.

Examples
--------
Process all VP folders under the default root:
    python3 extract_eyelink_blink_benchmark_v1_1.py

Process one VP:
    python3 extract_eyelink_blink_benchmark_v1_1.py --vp beo7

Use another root:
    python3 extract_eyelink_blink_benchmark_v1_1.py \
        --root /Volumes/Empra9/Ergebnisse25 --vp beo7

Test one ASC file outside the project directory:
    python3 extract_eyelink_blink_benchmark_v1_1.py \
        --asc /path/to/file.asc \
        --vp-code beo7 \
        --output-dir /path/to/test25
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from dataclasses import dataclass, fields
from pathlib import Path
from typing import Iterable, Optional

HZ = 60
EMPRA = 10

DEFAULT_ROOT = Path(f"/Volumes/Empra{EMPRA}/Ergebnisse{HZ}")
DEFAULT_OUTPUT_SUBDIR = f"test{HZ}"
BLINK_OUTPUT_NAME = "eyelink_blink_benchmark.csv"
MARKER_OUTPUT_NAME = "eyelink_trial_markers.csv"

# Matches, for example:
# MSG 11753195 start_fixation_1
# MSG 11755934 start_trial_1
# Tabs and multiple spaces are both accepted.
TRIAL_MSG_RE = re.compile(
    r"^MSG\s+(?P<timestamp>\d+)\s+"
    r"(?P<marker>start_fixation|end_fixation|start_trial|end_trial)_"
    r"(?P<trial>practice|\d+)\s*$",
    flags=re.IGNORECASE,
)

SAMPLE_RATE_PATTERNS = (
    re.compile(r"^SAMPLES\b.*\bRATE\s+(?P<rate>\d+(?:\.\d+)?)", re.IGNORECASE),
    re.compile(r"^EVENTS\b.*\bRATE\s+(?P<rate>\d+(?:\.\d+)?)", re.IGNORECASE),
    re.compile(r"^RECCFG\s+\S+\s+(?P<rate>\d+(?:\.\d+)?)", re.IGNORECASE),
)


@dataclass(frozen=True)
class BlinkEvent:
    eye: str
    start_tracker_ms: int
    end_tracker_ms: int
    duration_ms: int
    asc_line_number: int


@dataclass
class TrialMarkers:
    trial: str
    start_fixation_tracker_ms: Optional[int] = None
    end_fixation_tracker_ms: Optional[int] = None
    start_trial_tracker_ms: Optional[int] = None
    end_trial_tracker_ms: Optional[int] = None

    @property
    def is_practice(self) -> bool:
        return self.trial == "practice"

    @property
    def complete(self) -> bool:
        return all(
            value is not None
            for value in (
                self.start_fixation_tracker_ms,
                self.end_fixation_tracker_ms,
                self.start_trial_tracker_ms,
                self.end_trial_tracker_ms,
            )
        )


@dataclass(frozen=True)
class ParsedAsc:
    blinks: list[BlinkEvent]
    trials: dict[str, TrialMarkers]
    sblink_count: int
    sample_rate_hz: Optional[float]


class AscFormatError(ValueError):
    """Raised when an ASC line required for analysis is malformed."""


def trial_sort_key(trial: str) -> tuple[int, int]:
    """Place practice first, then sort formal trials numerically."""
    if trial == "practice":
        return (0, 0)
    return (1, int(trial))


def parse_int(text: str, *, line_number: int, field_name: str) -> int:
    try:
        return int(text)
    except ValueError as exc:
        raise AscFormatError(
            f"Line {line_number}: invalid {field_name} value {text!r}."
        ) from exc


def update_trial_marker(
    trials: dict[str, TrialMarkers],
    *,
    trial_name: str,
    marker_name: str,
    timestamp_ms: int,
    line_number: int,
) -> None:
    """Store one trial marker and reject conflicting duplicates."""
    trial = trials.setdefault(trial_name, TrialMarkers(trial=trial_name))
    attribute = f"{marker_name}_tracker_ms"
    previous = getattr(trial, attribute)

    if previous is not None and previous != timestamp_ms:
        raise AscFormatError(
            f"Line {line_number}: conflicting duplicate marker "
            f"{marker_name}_{trial_name}. Existing={previous}, new={timestamp_ms}."
        )

    setattr(trial, attribute, timestamp_ms)


def parse_asc(asc_file: Path) -> ParsedAsc:
    """Read EBLINK events, trial markers, and EyeLink sampling rate."""
    blinks: list[BlinkEvent] = []
    trials: dict[str, TrialMarkers] = {}
    sblink_count = 0
    sample_rate_hz: Optional[float] = None

    with asc_file.open("r", encoding="utf-8", errors="replace") as handle:
        for line_number, raw_line in enumerate(handle, start=1):
            line = raw_line.strip()
            if not line:
                continue

            if line.startswith("SBLINK"):
                # EBLINK already contains the full start/end interval.
                # SBLINK is counted only for consistency checks.
                sblink_count += 1
                continue

            if line.startswith("EBLINK"):
                parts = line.split()
                if len(parts) < 5:
                    raise AscFormatError(
                        f"Line {line_number}: malformed EBLINK line: {line!r}"
                    )

                start_ms = parse_int(
                    parts[2], line_number=line_number, field_name="blink start"
                )
                end_ms = parse_int(
                    parts[3], line_number=line_number, field_name="blink end"
                )
                duration_ms = parse_int(
                    parts[4], line_number=line_number, field_name="blink duration"
                )

                if end_ms < start_ms:
                    raise AscFormatError(
                        f"Line {line_number}: EBLINK end precedes start: {line!r}"
                    )

                blinks.append(
                    BlinkEvent(
                        eye=parts[1],
                        start_tracker_ms=start_ms,
                        end_tracker_ms=end_ms,
                        duration_ms=duration_ms,
                        asc_line_number=line_number,
                    )
                )
                continue

            marker_match = TRIAL_MSG_RE.match(line)
            if marker_match:
                timestamp_ms = int(marker_match.group("timestamp"))
                marker_name = marker_match.group("marker").lower()
                trial_name = marker_match.group("trial").lower()
                update_trial_marker(
                    trials,
                    trial_name=trial_name,
                    marker_name=marker_name,
                    timestamp_ms=timestamp_ms,
                    line_number=line_number,
                )
                continue

            if sample_rate_hz is None:
                for pattern in SAMPLE_RATE_PATTERNS:
                    rate_match = pattern.match(line)
                    if rate_match:
                        sample_rate_hz = float(rate_match.group("rate"))
                        break

    return ParsedAsc(
        blinks=blinks,
        trials=trials,
        sblink_count=sblink_count,
        sample_rate_hz=sample_rate_hz,
    )


def interval_overlap_ms(
    start_a: int,
    end_a: int,
    start_b: int,
    end_b: int,
) -> int:
    return max(0, min(end_a, end_b) - max(start_a, start_b))


def assign_trial(
    blink: BlinkEvent,
    trials: dict[str, TrialMarkers],
) -> Optional[TrialMarkers]:
    """Assign an EBLINK to the trial window with the greatest overlap."""
    candidates: list[tuple[int, TrialMarkers]] = []

    for trial in trials.values():
        if (
            trial.start_fixation_tracker_ms is None
            or trial.end_trial_tracker_ms is None
        ):
            continue

        overlap = interval_overlap_ms(
            blink.start_tracker_ms,
            blink.end_tracker_ms,
            trial.start_fixation_tracker_ms,
            trial.end_trial_tracker_ms,
        )

        # Zero-duration EBLINK events can still lie inside a trial.
        point_inside = (
            blink.start_tracker_ms == blink.end_tracker_ms
            and trial.start_fixation_tracker_ms
            <= blink.start_tracker_ms
            <= trial.end_trial_tracker_ms
        )

        if overlap > 0 or point_inside:
            candidates.append((overlap, trial))

    if not candidates:
        return None

    # Prefer the greatest temporal overlap. Trial order is a deterministic tie-break.
    candidates.sort(
        key=lambda item: (item[0], trial_sort_key(item[1].trial)),
        reverse=True,
    )
    return candidates[0][1]


def classify_phase(
    blink: BlinkEvent,
    trial: Optional[TrialMarkers],
) -> str:
    """Describe which experimental phase(s) the interval overlaps.

    This is contextual metadata only. It does not filter or reclassify the
    EyeLink event: every EBLINK remains a benchmark blink event.
    """
    if trial is None or not trial.complete:
        return "outside_trial"

    assert trial.start_fixation_tracker_ms is not None
    assert trial.end_fixation_tracker_ms is not None
    assert trial.start_trial_tracker_ms is not None
    assert trial.end_trial_tracker_ms is not None

    segments = (
        (
            "fixation",
            trial.start_fixation_tracker_ms,
            trial.end_fixation_tracker_ms,
        ),
        (
            "transition_gap",
            trial.end_fixation_tracker_ms,
            trial.start_trial_tracker_ms,
        ),
        (
            "stimulus",
            trial.start_trial_tracker_ms,
            trial.end_trial_tracker_ms,
        ),
    )

    overlaps: list[str] = []
    for name, segment_start, segment_end in segments:
        overlap = interval_overlap_ms(
            blink.start_tracker_ms,
            blink.end_tracker_ms,
            segment_start,
            segment_end,
        )
        point_inside = (
            blink.start_tracker_ms == blink.end_tracker_ms
            and segment_start <= blink.start_tracker_ms <= segment_end
        )
        if overlap > 0 or point_inside:
            overlaps.append(name)

    return "+".join(overlaps) if overlaps else "outside_trial"


def relative_ms(value_ms: int, origin_ms: Optional[int]) -> Optional[int]:
    if origin_ms is None:
        return None
    return value_ms - origin_ms


def milliseconds_to_seconds(value_ms: Optional[int]) -> Optional[float]:
    if value_ms is None:
        return None
    return value_ms / 1000.0


def blink_rows(
    *,
    parsed: ParsedAsc,
    vp_code: str,
    asc_file: Path,
) -> Iterable[dict[str, object]]:
    for event_index, blink in enumerate(parsed.blinks, start=1):
        trial = assign_trial(blink, parsed.trials)

        fixation_origin = (
            trial.start_fixation_tracker_ms if trial is not None else None
        )
        stimulus_origin = (
            trial.start_trial_tracker_ms if trial is not None else None
        )

        start_from_fixation_ms = relative_ms(
            blink.start_tracker_ms, fixation_origin
        )
        end_from_fixation_ms = relative_ms(
            blink.end_tracker_ms, fixation_origin
        )
        start_from_stimulus_ms = relative_ms(
            blink.start_tracker_ms, stimulus_origin
        )
        end_from_stimulus_ms = relative_ms(
            blink.end_tracker_ms, stimulus_origin
        )

        yield {
            "vp_code": vp_code,
            "asc_file": asc_file.name,
            "eyelink_sampling_rate_hz": parsed.sample_rate_hz,
            "event_index": event_index,
            "eye": blink.eye,
            "start_tracker_ms": blink.start_tracker_ms,
            "end_tracker_ms": blink.end_tracker_ms,
            "duration_ms": blink.duration_ms,
            "asc_line_number": blink.asc_line_number,
            "trial": trial.trial if trial is not None else None,
            "is_practice": trial.is_practice if trial is not None else None,
            "phase": classify_phase(blink, trial),
            "fixation_start_tracker_ms": (
                trial.start_fixation_tracker_ms if trial is not None else None
            ),
            "fixation_end_tracker_ms": (
                trial.end_fixation_tracker_ms if trial is not None else None
            ),
            "stimulus_start_tracker_ms": (
                trial.start_trial_tracker_ms if trial is not None else None
            ),
            "stimulus_end_tracker_ms": (
                trial.end_trial_tracker_ms if trial is not None else None
            ),
            "start_from_fixation_ms": start_from_fixation_ms,
            "end_from_fixation_ms": end_from_fixation_ms,
            "start_from_fixation_s": milliseconds_to_seconds(
                start_from_fixation_ms
            ),
            "end_from_fixation_s": milliseconds_to_seconds(
                end_from_fixation_ms
            ),
            "start_from_stimulus_ms": start_from_stimulus_ms,
            "end_from_stimulus_ms": end_from_stimulus_ms,
            "start_from_stimulus_s": milliseconds_to_seconds(
                start_from_stimulus_ms
            ),
            "end_from_stimulus_s": milliseconds_to_seconds(
                end_from_stimulus_ms
            ),
        }


def marker_rows(
    *,
    parsed: ParsedAsc,
    vp_code: str,
    asc_file: Path,
) -> Iterable[dict[str, object]]:
    for trial in sorted(parsed.trials.values(), key=lambda item: trial_sort_key(item.trial)):
        fixation_duration_ms = (
            trial.end_fixation_tracker_ms - trial.start_fixation_tracker_ms
            if trial.start_fixation_tracker_ms is not None
            and trial.end_fixation_tracker_ms is not None
            else None
        )
        transition_gap_ms = (
            trial.start_trial_tracker_ms - trial.end_fixation_tracker_ms
            if trial.end_fixation_tracker_ms is not None
            and trial.start_trial_tracker_ms is not None
            else None
        )
        stimulus_duration_ms = (
            trial.end_trial_tracker_ms - trial.start_trial_tracker_ms
            if trial.start_trial_tracker_ms is not None
            and trial.end_trial_tracker_ms is not None
            else None
        )

        yield {
            "vp_code": vp_code,
            "asc_file": asc_file.name,
            "eyelink_sampling_rate_hz": parsed.sample_rate_hz,
            "trial": trial.trial,
            "is_practice": trial.is_practice,
            "complete_marker_set": trial.complete,
            "fixation_start_tracker_ms": trial.start_fixation_tracker_ms,
            "fixation_end_tracker_ms": trial.end_fixation_tracker_ms,
            "stimulus_start_tracker_ms": trial.start_trial_tracker_ms,
            "stimulus_end_tracker_ms": trial.end_trial_tracker_ms,
            "fixation_duration_ms": fixation_duration_ms,
            "transition_gap_ms": transition_gap_ms,
            "stimulus_duration_ms": stimulus_duration_ms,
        }


def write_csv(
    output_file: Path,
    rows: Iterable[dict[str, object]],
    fieldnames: list[str],
) -> int:
    output_file.parent.mkdir(parents=True, exist_ok=True)
    count = 0

    with output_file.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
            count += 1

    return count


def find_vp_asc(vp_dir: Path, vp_code: str) -> Path:
    """Find exactly one ASC whose filename starts with the VP code."""
    prefix_matches = sorted(
        path
        for path in vp_dir.glob(f"{vp_code}*.asc")
        if path.is_file()
    )

    if len(prefix_matches) == 1:
        return prefix_matches[0]

    if len(prefix_matches) > 1:
        names = "\n  ".join(path.name for path in prefix_matches)
        raise FileExistsError(
            f"Multiple ASC files start with {vp_code!r} in {vp_dir}:\n  {names}"
        )

    # Case-insensitive fallback, useful when folder and file casing differ.
    casefold_matches = sorted(
        path
        for path in vp_dir.glob("*.asc")
        if path.is_file() and path.name.casefold().startswith(vp_code.casefold())
    )

    if len(casefold_matches) == 1:
        return casefold_matches[0]

    if len(casefold_matches) > 1:
        names = "\n  ".join(path.name for path in casefold_matches)
        raise FileExistsError(
            f"Multiple case-insensitive ASC matches for {vp_code!r}:\n  {names}"
        )

    raise FileNotFoundError(
        f"No ASC file matching {vp_code}*.asc found in {vp_dir}"
    )


def process_one_asc(
    *,
    asc_file: Path,
    vp_code: str,
    output_dir: Path,
) -> dict[str, object]:
    parsed = parse_asc(asc_file)

    blink_output = output_dir / BLINK_OUTPUT_NAME
    marker_output = output_dir / MARKER_OUTPUT_NAME

    blink_fieldnames = [
        "vp_code",
        "asc_file",
        "eyelink_sampling_rate_hz",
        "event_index",
        "eye",
        "start_tracker_ms",
        "end_tracker_ms",
        "duration_ms",
        "asc_line_number",
        "trial",
        "is_practice",
        "phase",
        "fixation_start_tracker_ms",
        "fixation_end_tracker_ms",
        "stimulus_start_tracker_ms",
        "stimulus_end_tracker_ms",
        "start_from_fixation_ms",
        "end_from_fixation_ms",
        "start_from_fixation_s",
        "end_from_fixation_s",
        "start_from_stimulus_ms",
        "end_from_stimulus_ms",
        "start_from_stimulus_s",
        "end_from_stimulus_s",
    ]

    marker_fieldnames = [
        "vp_code",
        "asc_file",
        "eyelink_sampling_rate_hz",
        "trial",
        "is_practice",
        "complete_marker_set",
        "fixation_start_tracker_ms",
        "fixation_end_tracker_ms",
        "stimulus_start_tracker_ms",
        "stimulus_end_tracker_ms",
        "fixation_duration_ms",
        "transition_gap_ms",
        "stimulus_duration_ms",
    ]

    blink_count = write_csv(
        blink_output,
        blink_rows(parsed=parsed, vp_code=vp_code, asc_file=asc_file),
        blink_fieldnames,
    )
    marker_count = write_csv(
        marker_output,
        marker_rows(parsed=parsed, vp_code=vp_code, asc_file=asc_file),
        marker_fieldnames,
    )

    assigned_count = sum(
        1 for blink in parsed.blinks if assign_trial(blink, parsed.trials) is not None
    )
    complete_trial_count = sum(trial.complete for trial in parsed.trials.values())

    return {
        "vp_code": vp_code,
        "asc_file": asc_file,
        "blink_output": blink_output,
        "marker_output": marker_output,
        "eblink_count": blink_count,
        "sblink_count": parsed.sblink_count,
        "assigned_blink_count": assigned_count,
        "outside_blink_count": blink_count - assigned_count,
        "marker_count": marker_count,
        "complete_trial_count": complete_trial_count,
        "sample_rate_hz": parsed.sample_rate_hz,
    }


def directory_has_matching_asc(vp_dir: Path) -> bool:
    """Return True only when a directory looks like a VP directory.

    A valid VP directory must contain at least one ASC file whose filename
    starts with the directory name, for example:
        .../beo7/beo7123456.asc

    This prevents unrelated output directories such as
    ``Figure7_new_blink_filter`` from being treated as participants.
    Multiple matching ASC files are still included here and will later raise
    a clear error in ``find_vp_asc``.
    """
    vp_code = vp_dir.name.casefold()
    return any(
        path.is_file()
        and path.suffix.casefold() == ".asc"
        and path.name.casefold().startswith(vp_code)
        for path in vp_dir.iterdir()
    )


def discover_vp_directories(root: Path) -> tuple[list[Path], list[Path]]:
    """Find VP directories and separately report unrelated directories."""
    vp_dirs: list[Path] = []
    skipped_dirs: list[Path] = []

    for path in sorted(root.iterdir()):
        if not path.is_dir() or path.name.startswith("."):
            continue

        if directory_has_matching_asc(path):
            vp_dirs.append(path)
        else:
            skipped_dirs.append(path)

    return vp_dirs, skipped_dirs


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Extract every EyeLink EBLINK interval and export trial-relative "
            "blink benchmark CSV files."
        )
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_ROOT,
        help=f"Ergebnisse25 root. Default: {DEFAULT_ROOT}",
    )
    parser.add_argument(
        "--vp",
        action="append",
        default=None,
        help=(
            "VP folder name to process. May be supplied multiple times. "
            "Omit to scan all VP folders under --root."
        ),
    )
    parser.add_argument(
        "--asc",
        type=Path,
        default=None,
        help="Process one explicit ASC file instead of scanning --root.",
    )
    parser.add_argument(
        "--vp-code",
        default=None,
        help="VP code used with --asc. Defaults to the ASC parent-folder name.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help=(
            "Output directory used with --asc. Defaults to "
            "<ASC parent>/test25."
        ),
    )
    parser.add_argument(
        "--continue-on-error",
        action="store_true",
        help="In batch mode, report a failed VP and continue with the others.",
    )
    return parser


def print_summary(summary: dict[str, object]) -> None:
    print(f"\n[OK] VP: {summary['vp_code']}")
    print(f"  ASC:              {summary['asc_file']}")
    print(f"  EyeLink rate:     {summary['sample_rate_hz']} Hz")
    print(
        f"  EBLINK / SBLINK:  {summary['eblink_count']} / "
        f"{summary['sblink_count']}"
    )
    print(
        f"  Trial-assigned:   {summary['assigned_blink_count']} "
        f"(outside: {summary['outside_blink_count']})"
    )
    print(
        f"  Complete trials:  {summary['complete_trial_count']} / "
        f"{summary['marker_count']} marker sets"
    )
    print(f"  Blink CSV:        {summary['blink_output']}")
    print(f"  Marker CSV:       {summary['marker_output']}")


def main() -> int:
    parser = build_argument_parser()
    args = parser.parse_args()

    try:
        if args.asc is not None:
            asc_file = args.asc.expanduser().resolve()
            if not asc_file.is_file():
                raise FileNotFoundError(f"ASC file does not exist: {asc_file}")

            vp_code = args.vp_code or asc_file.parent.name
            output_dir = (
                args.output_dir.expanduser().resolve()
                if args.output_dir is not None
                else asc_file.parent / DEFAULT_OUTPUT_SUBDIR
            )

            summary = process_one_asc(
                asc_file=asc_file,
                vp_code=vp_code,
                output_dir=output_dir,
            )
            print_summary(summary)
            return 0

        root = args.root.expanduser().resolve()
        if not root.is_dir():
            raise FileNotFoundError(f"Root directory does not exist: {root}")

        if args.vp:
            vp_dirs = [root / vp_code for vp_code in args.vp]
        else:
            vp_dirs, skipped_dirs = discover_vp_directories(root)
            for skipped_dir in skipped_dirs:
                print(
                    "[SKIP] Not a VP directory or no matching ASC: "
                    f"{skipped_dir.name}"
                )

        if not vp_dirs:
            raise FileNotFoundError(
                "No VP directories containing <VP_NAME>*.asc were found under: "
                f"{root}"
            )

        processed = 0
        failed = 0

        for vp_dir in vp_dirs:
            vp_code = vp_dir.name
            try:
                if not vp_dir.is_dir():
                    raise FileNotFoundError(f"VP directory does not exist: {vp_dir}")

                asc_file = find_vp_asc(vp_dir, vp_code)
                output_dir = vp_dir / DEFAULT_OUTPUT_SUBDIR
                summary = process_one_asc(
                    asc_file=asc_file,
                    vp_code=vp_code,
                    output_dir=output_dir,
                )
                print_summary(summary)
                processed += 1

            except Exception as exc:  # noqa: BLE001 - per-VP batch reporting
                failed += 1
                print(
                    f"\n[ERROR] VP {vp_code}: {type(exc).__name__}: {exc}",
                    file=sys.stderr,
                )
                if not args.continue_on_error:
                    raise

        print(
            f"\nFinished. Successful VPs: {processed}; failed VPs: {failed}."
        )
        return 0 if failed == 0 else 1

    except Exception as exc:  # noqa: BLE001 - CLI error boundary
        print(f"\n[FATAL] {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())